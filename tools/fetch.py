"""Recreate the benchmark from manifest.toml.

For every project: clone it into ../_checkouts/<name> at the pinned commit,
build its own venv in ../_checkouts/_venvs/<name> (pytest, pytest-timeout,
coverage, the project's test dependencies, and the project itself installed
non-editable), and write targets/<id>.toml for testloop.

The project is installed non-editable on purpose: testloop puts the workspace
copy first on PYTHONPATH, so mutants are imported from the copy, while the
installed package still provides metadata (importlib.metadata.version).

    python tools/fetch.py              # everything
    python tools/fetch.py --only toolz # one project
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
CHECKOUTS = HERE.parent / "_checkouts"
HARNESS_DEPS = ["pytest>=8", "pytest-timeout>=2.3", "coverage>=7.4"]


def run(*cmd: str, cwd: Path | None = None) -> None:
    subprocess.run(cmd, cwd=cwd, check=True)


def checkout(project: dict) -> Path:
    dest = CHECKOUTS / project["name"]
    if not dest.exists():
        run("git", "clone", "--quiet", "--filter=blob:none", project["repo"], str(dest))
    have = subprocess.run(["git", "-C", str(dest), "rev-parse", "HEAD"], capture_output=True,
                          text=True).stdout.strip()
    if have != project["commit"]:
        run("git", "-C", str(dest), "fetch", "--quiet", "--depth", "1", "origin", project["commit"])
        run("git", "-C", str(dest), "checkout", "--quiet", "--detach", project["commit"])
    return dest


def venv(project: dict, src: Path) -> Path:
    env = CHECKOUTS / "_venvs" / project["name"]
    py = env / "bin" / "python"
    if not py.exists():
        run(sys.executable, "-m", "venv", str(env))
    run(str(py), "-m", "pip", "install", "--quiet", "--upgrade", "pip")
    run(str(py), "-m", "pip", "install", "--quiet", *HARNESS_DEPS, *project.get("test_deps", []),
        str(src))
    return py


def write_target(project: dict, target: dict) -> Path:
    path = HERE / "targets" / f"{target['id']}.toml"
    q = lambda v: json.dumps(v, ensure_ascii=False)  # noqa: E731  (TOML-compatible literals)
    path.write_text("\n".join([
        f"# Generated by tools/fetch.py from manifest.toml ({project['name']} @ {project['commit'][:7]}).",
        "[target]",
        f"name = {q(target['id'])}",
        f"project_root = {q('../../_checkouts/' + project['name'])}",
        f"module_file = {q(target['module_file'])}",
        f"module_name = {q(target['module_name'])}",
        f"python_path = {q(target['python_path'])}",
        f"human_tests = {q(target['human_tests'])}",
        f"python = {q('../../_checkouts/_venvs/' + project['name'] + '/bin/python')}",
        "",
    ]), encoding="utf-8")
    return path


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--only", nargs="*", help="project names")
    p.add_argument("--no-install", action="store_true", help="clone and write targets only")
    args = p.parse_args()
    manifest = tomllib.loads((HERE / "manifest.toml").read_text(encoding="utf-8"))
    (HERE / "targets").mkdir(exist_ok=True)
    failed = []
    for project in manifest["project"]:
        if args.only and project["name"] not in args.only:
            continue
        try:
            src = checkout(project)
            if not args.no_install:
                venv(project, src)
            for target in project["target"]:
                if target.get("status") != "rejected":
                    write_target(project, target)
            print(f"ok   {project['name']} @ {project['commit'][:7]}")
        except subprocess.CalledProcessError as exc:
            failed.append(project["name"])
            print(f"FAIL {project['name']}: {exc}", file=sys.stderr)
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
