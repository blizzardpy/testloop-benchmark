"""Recreate the benchmark from manifest.toml.

For every project: clone it into ../_checkouts/<name> at the pinned commit,
build its own venv in ../_checkouts/_venvs/<name> (pytest, pytest-timeout,
coverage, the project's test dependencies, and the project itself installed
non-editable), and write targets/<id>.toml for testloop.

The project is installed non-editable on purpose: testloop puts the workspace
copy first on PYTHONPATH, so mutants are imported from the copy, while the
installed package still provides metadata (importlib.metadata.version).

    python tools/fetch.py              # everything
    python tools/fetch.py --only toolz # one project
    python tools/fetch.py --pynguin    # also a Pynguin venv per project (../_checkouts/_venvs/<name>-pynguin)
    python tools/fetch.py --tier postcutoff  # the post-cutoff tier: manifest-postcutoff.toml -> targets-postcutoff/

Pynguin pins its own pytest, so it gets a venv of its own with the project
installed beside it; the project's test venv is left alone.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
CHECKOUTS = HERE.parent / "_checkouts"
HARNESS_DEPS = ["pytest==9.1.1", "pytest-timeout==2.4.0", "coverage==7.16.2"]  # versions in the benchmark-v1 venvs
PYNGUIN = "pynguin==0.48.0"


def run(*cmd: str, cwd: Path | None = None) -> None:
    subprocess.run(cmd, cwd=cwd, check=True)


def checkout(project: dict) -> Path:
    dest = CHECKOUTS / project["name"]
    if not dest.exists():
        run("git", "clone", "--quiet", "--filter=blob:none", project["repo"], str(dest))
    have = subprocess.run(["git", "-C", str(dest), "rev-parse", "HEAD"], capture_output=True,
                          text=True).stdout.strip()
    if have != project["commit"]:
        run("git", "-C", str(dest), "fetch", "--quiet", "--depth", "1", "origin", project["commit"])
        run("git", "-C", str(dest), "checkout", "--quiet", "--detach", project["commit"])
    return dest


def tier_paths(tier: str) -> tuple[Path, Path]:
    """(manifest, targets dir) of a tier; v1 is the frozen main tier."""
    if tier == "v1":
        return HERE / "manifest.toml", HERE / "targets"
    return HERE / f"manifest-{tier}.toml", HERE / f"targets-{tier}"


def venv(project: dict, src: Path) -> Path:
    src = src / project.get("subdir", "")  # package not at the repo root
    env = CHECKOUTS / "_venvs" / project["name"]
    py = env / "bin" / "python"
    if not py.exists():
        run(sys.executable, "-m", "venv", str(env))
    run(str(py), "-m", "pip", "install", "--quiet", "--upgrade", "pip")
    run(str(py), "-m", "pip", "install", "--quiet", *HARNESS_DEPS, *project.get("test_deps", []),
        str(src))
    return py


def pynguin_venv(project: dict, src: Path) -> Path:
    env = CHECKOUTS / "_venvs" / f"{project['name']}-pynguin"
    py = env / "bin" / "python"
    if not py.exists():
        run(sys.executable, "-m", "venv", str(env))
    run(str(py), "-m", "pip", "install", "--quiet", "--upgrade", "pip")
    # Same runtime packages as the test venv (test_deps can pull in optional
    # extras such as brotli that change module constants), minus the harness's
    # pytest, which Pynguin pins to an older major.
    run(str(py), "-m", "pip", "install", "--quiet", PYNGUIN, *project.get("test_deps", []), str(src))
    return py


def write_target(project: dict, target: dict, targets: Path, manifest_name: str) -> Path:
    path = targets / f"{target['id']}.toml"
    q = lambda v: json.dumps(v, ensure_ascii=False)  # noqa: E731  (TOML-compatible literals)
    path.write_text("\n".join([
        f"# Generated by tools/fetch.py from {manifest_name} ({project['name']} @ {project['commit'][:7]}).",
        "[target]",
        f"name = {q(target['id'])}",
        f"project_root = {q('/'.join(filter(None, ['../../_checkouts', project['name'], project.get('subdir')])))}",
        f"module_file = {q(target['module_file'])}",
        f"module_name = {q(target['module_name'])}",
        f"python_path = {q(target['python_path'])}",
        f"human_tests = {q(target['human_tests'])}",
        f"python = {q('../../_checkouts/_venvs/' + project['name'] + '/bin/python')}",
        "",
    ]), encoding="utf-8")
    return path


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--only", nargs="*", help="project names")
    p.add_argument("--no-install", action="store_true", help="clone and write targets only")
    p.add_argument("--pynguin", action="store_true", help="also build each project's Pynguin venv")
    p.add_argument("--tier", default="v1", help="v1 (default) or postcutoff")
    args = p.parse_args()
    manifest_path, targets = tier_paths(args.tier)
    manifest = tomllib.loads(manifest_path.read_text(encoding="utf-8"))
    targets.mkdir(exist_ok=True)
    failed = []
    for project in manifest["project"]:
        if args.only and project["name"] not in args.only:
            continue
        try:
            src = checkout(project)
            if not args.no_install:
                venv(project, src)
                if args.pynguin:
                    pynguin_venv(project, src)
            for target in project["target"]:
                if target.get("status") != "rejected":
                    write_target(project, target, targets, manifest_path.name)
            print(f"ok   {project['name']} @ {project['commit'][:7]}")
        except subprocess.CalledProcessError as exc:
            failed.append(project["name"])
            print(f"FAIL {project['name']}: {exc}", file=sys.stderr)
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
